// CAD-1792: TypeScript for the board API, generated from the JSON Schema
// the daemon's Rust types emit (`contracts/board-api/v1/*.schema.json`).
// A small emitter for the subset schemars produces: $defs/$ref, nullable
// type arrays, anyOf/oneOf/allOf, enum/const, objects, arrays, and `true`
// (any value). `--check` fails when the committed output is stale.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "../../contracts/board-api/v1");
const out = join(here, "../src/lib/generated/board-api.ts");

const ref = (r) => r.replace("#/$defs/", "");
const doc = (node, pad) =>
  node && typeof node === "object" && node.description
    ? `${pad}/** ${node.description.replace(/\*\//g, "* /").split("\n").join(`\n${pad} * `)} */\n`
    : "";

function ts(node, pad) {
  if (node === true || node === undefined || Object.keys(node).length === 0) return "unknown";
  if (node === false) return "never";
  if (node.$ref) return ref(node.$ref);
  if (node.allOf) return node.allOf.map((n) => ts(n, pad)).join(" & ");
  const union = node.anyOf ?? node.oneOf;
  if (union) return [...new Set(union.map((n) => ts(n, pad)))].join(" | ");
  if (node.const !== undefined) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (node.type === undefined) return "unknown";
  const types = Array.isArray(node.type) ? node.type : [node.type];
  return [...new Set(types.map((t) => one(node, t, pad)))].join(" | ");
}

function one(node, type, pad) {
  switch (type) {
    case "string": return "string";
    case "integer":
    case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": return `${wrap(ts(node.items, pad))}[]`;
    case "object": return object(node, pad);
    default: throw new Error(`unsupported schema node: ${JSON.stringify(node)}`);
  }
}

const wrap = (t) => (/[|&]/.test(t) ? `(${t})` : t);

function object(node, pad) {
  const props = node.properties ?? {};
  const required = new Set(node.required ?? []);
  const keys = Object.keys(props).sort();
  const extra = node.additionalProperties;
  if (keys.length === 0 && extra && extra !== true) return `Record<string, ${ts(extra, pad)}>`;
  if (keys.length === 0) return "Record<string, unknown>";
  const inner = `${pad}  `;
  const body = keys
    .map((k) => `${doc(props[k], inner)}${inner}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}${required.has(k) ? "" : "?"}: ${ts(props[k], inner)};`)
    .join("\n");
  return `{\n${body}\n${pad}}`;
}

export function generate() {
  const defs = new Map();
  for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort()) {
    const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
    const { $defs = {}, title, ...root } = schema;
    delete root.$schema;
    for (const [name, def] of [...Object.entries($defs), [title, root]]) {
      const text = JSON.stringify(def);
      if (defs.has(name) && defs.get(name).text !== text) throw new Error(`${name} differs between schemas`);
      defs.set(name, { def, text });
    }
  }
  const lines = [
    "// Generated by ui/scripts/gen-board-api-types.mjs from contracts/board-api/v1/*.schema.json.",
    "// Do not edit: change the Rust types, then `CADENCE_CORE_WRITE_SCHEMA=1 cargo test -p cadence-core`",
    "// and `bun run --cwd ui gen:board-api`.",
    "",
  ];
  for (const name of [...defs.keys()].sort()) {
    const { def } = defs.get(name);
    const body = ts(def, "");
    lines.push(
      def.type === "object" && body.startsWith("{")
        ? `${doc(def, "")}export interface ${name} ${body}`
        : `${doc(def, "")}export type ${name} = ${body};`,
      "",
    );
  }
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(out, "utf8"); } catch {}
    if (current !== text) {
      console.error("ui/src/lib/generated/board-api.ts is stale; run `bun run --cwd ui gen:board-api`");
      process.exit(1);
    }
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
  }
}
