//! Provider-launch dispatch — split from `action_dispatch.rs` (CAD-1654).

use super::*;

pub(super) fn dispatch(state_dir: PathBuf, command: Commands) -> Result<i32> {
    match command {
        Commands::Devin {
            resume,
            detach,
            cwd,
            alias,
            role,
            team_role,
            instructions_file,
            worktree,
            bootstrap,
            no_bootstrap,
            auto_ready,
            agents_md,
            permission_mode,
            bypass,
            cloud,
            cloud_params,
        } => devin::run(
            state_dir,
            resume,
            detach,
            cwd,
            alias,
            role,
            team_role,
            instructions_file,
            worktree,
            bootstrap,
            no_bootstrap,
            auto_ready,
            agents_md,
            permission_mode,
            bypass,
            cloud,
            cloud_params,
        ),
        Commands::Codex {
            detach,
            cwd,
            alias,
            role,
            model,
            provider_default_model,
            team_role,
            effort,
            approval_policy,
            turn_idle_secs,
            turn_max_secs,
            sandbox,
            instructions_file,
            worktree,
            bootstrap,
            no_bootstrap,
            tui,
            agents_md,
        } => codex::run(
            state_dir,
            detach,
            cwd,
            alias,
            role,
            model,
            provider_default_model,
            team_role,
            effort,
            approval_policy,
            turn_idle_secs,
            turn_max_secs,
            sandbox,
            instructions_file,
            worktree,
            bootstrap,
            no_bootstrap,
            tui,
            agents_md,
        ),
        Commands::Claude {
            tui,
            resume,
            cwd,
            alias,
            role,
            model,
            provider_default_model,
            team_role,
            effort,
            permission_mode,
            allow,
            bypass,
            broker_approvals,
            permission_timeout_secs,
            turn_idle_secs,
            turn_max_secs,
            instructions_file,
            worktree,
            bootstrap,
            no_bootstrap,
            auto_ready,
            detach,
            agents_md,
        } => claude::run(
            state_dir,
            tui,
            resume,
            cwd,
            alias,
            role,
            model,
            provider_default_model,
            team_role,
            effort,
            permission_mode,
            allow,
            bypass,
            broker_approvals,
            permission_timeout_secs,
            turn_idle_secs,
            turn_max_secs,
            instructions_file,
            worktree,
            bootstrap,
            no_bootstrap,
            auto_ready,
            detach,
            agents_md,
        ),
        Commands::Cursor {
            resume,
            detach,
            cwd,
            alias,
            role,
            model,
            provider_default_model,
            team_role,
            permission_mode,
            bypass,
            instructions_file,
            worktree,
            bootstrap,
            no_bootstrap,
            auto_ready,
            agents_md,
        } => cursor::run(
            state_dir,
            resume,
            detach,
            cwd,
            alias,
            role,
            model,
            provider_default_model,
            team_role,
            permission_mode,
            bypass,
            instructions_file,
            worktree,
            bootstrap,
            no_bootstrap,
            auto_ready,
            agents_md,
        ),
        _ => unreachable!("providers dispatch received a non-provider command"),
    }
}
