//! Administrative and maintenance dispatch — split from `action_dispatch.rs` (CAD-1654).

use super::*;

pub(super) fn dispatch(state_dir: PathBuf, command: Commands) -> Result<i32> {
    match command {
        Commands::InspectPortable { source } => {
            print_json(&cadence_agent::backup::portable::inspect_portable(&source)?);
            Ok(0)
        }
        Commands::Doctor {
            host,
            json,
            reclaim_plan,
        } => doctor::run(state_dir, host, json, reclaim_plan),
        Commands::Setup {
            json,
            port,
            no_open,
        } => setup::run(state_dir, json, port, no_open),
        Commands::Daemon { action } => daemon::run(state_dir, action),
        Commands::Rollout { action } => rollout::run(state_dir, action),
        Commands::Staging { action } => staging::run(state_dir, action),
        Commands::Backup { dir, keep, reason } => backup::run(state_dir, dir, keep, reason),
        Commands::Export {
            out,
            portable,
            tracker,
            apps,
            snapshot_working_tree,
            redact_history_secrets,
        } => export::run(
            state_dir,
            out,
            portable,
            tracker,
            apps,
            snapshot_working_tree,
            redact_history_secrets,
        ),
        Commands::Restore {
            source,
            repos,
            force,
            portable,
            preflight,
            replace,
            controller_state,
            expected_package_digest,
            expected_destination_digest,
            expected_generation,
            activate,
            reconciliation,
            request_id,
            status,
            rollback,
        } => restore::run(restore::Options {
            state_dir,
            source,
            repos,
            force,
            portable,
            preflight,
            replace: restore::Replace {
                enabled: replace,
                controller_state,
                expected_package_digest,
                expected_destination_digest,
                expected_generation,
            },
            activate: restore::Activation {
                enabled: activate,
                reconciliation,
            },
            request_id,
            status,
            rollback,
        }),
        Commands::Upgrade {
            sha,
            latest_main,
            dry_run,
            restart,
            as_identity,
            allow_unattested,
            repo,
            link,
            releases_dir,
            release_source,
        } => upgrade::run(
            state_dir,
            sha,
            latest_main,
            dry_run,
            restart,
            as_identity,
            allow_unattested,
            repo,
            link,
            releases_dir,
            release_source,
        ),
        Commands::Update {
            action,
            version: _,
            check,
            rollback,
            drain,
            now,
            keep,
            backup_dir,
            json,
            progress,
            to,
            target,
        } => update::run(
            state_dir, action, check, rollback, drain, now, keep, backup_dir, json, progress, to,
            target,
        ),
        Commands::Test { action } => test_cmd::run(&state_dir, &action),
        Commands::BuildSlot { action } => build_slot::run(state_dir, action),
        Commands::Confine {
            read,
            write,
            command,
        } => confine::run(state_dir, read, write, command),
        Commands::Dev { action } => sandbox::run(state_dir, action),
        _ => unreachable!("admin dispatch received a non-admin command"),
    }
}
