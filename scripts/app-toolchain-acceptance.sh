#!/usr/bin/env bash
# Independent CAD-1272 end-to-end acceptance. Requires an actual built cadence CLI
# and pnpm 12.2.1 already available; it never builds Rust or installs pnpm.
set -euo pipefail

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cli=${1:?usage: scripts/app-toolchain-acceptance.sh /path/to/built/cadence}
cli=$(cd "$(dirname "$cli")" && pwd)/$(basename "$cli")
[[ -x "$cli" ]] || { echo "not an executable cadence CLI: $cli" >&2; exit 2; }

version=$($cli --version)
if [[ ! $version =~ ^cadence[[:space:]]+([^[:space:]]+)\+([0-9a-f]{40})$ ]]; then
  echo "CLI version must be 'cadence <version>+<full-source-sha>', got: $version" >&2
  exit 1
fi
release_version=${BASH_REMATCH[1]}
source_sha=${BASH_REMATCH[2]}
tag="v$release_version"
[[ $(pnpm --version) == 12.2.1 ]] || { echo 'acceptance requires pnpm 12.2.1' >&2; exit 1; }

work=$(mktemp -d "${TMPDIR:-/tmp}/cad1272-app-toolchain.XXXXXX")
trap 'rm -rf "$work"' EXIT
out="$work/package-out"
"$repo/scripts/package-app-toolchain" --cadence "$cli" --tag "$tag" --source-sha "$source_sha" --out "$out"
asset="cadence-app-toolchain-${tag}.tar.gz"
archive="$out/$asset"
sidecar="$archive.sha256"
test -f "$archive" && test -f "$sidecar"
(cd "$out" && sha256sum -c "$asset.sha256")

# The archive is a fixed consumer surface, not a snapshot of the checkout.
expected_members=$(printf '%s\n' LICENSE README.md frame-kit/frame.html frame-kit/kit.css frame-kit/metadata.json package.json pnpm-lock.yaml toolchain.json app-kit/README.md app-kit/package.json app-kit/src/index.mjs app-kit/src/receiver.mjs app-kit/src/refusal.mjs app-kit/types/index.d.ts | sort)
actual_members=$(tar -tzf "$archive" | sort)
if [[ "$actual_members" != "$expected_members" ]]; then
  printf 'unexpected toolchain archive members\nexpected:\n%s\nactual:\n%s\n' "$expected_members" "$actual_members" >&2
  exit 1
fi
mkdir "$work/unpacked"
tar -xzf "$archive" -C "$work/unpacked"

# Compare the packaged frame byte-for-byte with a fresh export from this same CLI.
"$cli" app frame-kit --out "$work/cli-frame"
for file in frame.html kit.css metadata.json; do
  cmp "$work/cli-frame/$file" "$work/unpacked/frame-kit/$file"
done
# The receiver is vendored byte-for-byte, never regenerated by the packager.
for file in README.md package.json src/index.mjs src/receiver.mjs src/refusal.mjs types/index.d.ts; do
  cmp "$repo/ui/app-kit/$file" "$work/unpacked/app-kit/$file"
done

python3 - "$repo/ui/package.json" "$work/unpacked/package.json" "$work/unpacked/toolchain.json" "$tag" "$source_sha" <<'PY'
import hashlib, json, sys
from pathlib import Path
ui_path, package_path, metadata_path, tag, source_sha = sys.argv[1:]
ui = json.loads(Path(ui_path).read_text())
pkg = json.loads(Path(package_path).read_text())
meta = json.loads(Path(metadata_path).read_text())
expected = {
    "react": ui["dependencies"]["react"],
    "react-dom": ui["dependencies"]["react-dom"],
}
expected_dev = {
    "@vitejs/plugin-react": ui["devDependencies"]["@vitejs/plugin-react"],
    "vite": ui["devDependencies"]["vite"],
}
expected_pins = {**ui["dependencies"], **ui["devDependencies"]}
expected_pins = {name: expected_pins[name] for name in ("react", "react-dom", "vite", "@vitejs/plugin-react")}
assert pkg["dependencies"] == expected, (pkg.get("dependencies"), expected)
assert pkg["devDependencies"] == expected_dev, (pkg.get("devDependencies"), expected_dev)
assert pkg["packageManager"] == ui["packageManager"] == "pnpm@12.2.1"
assert pkg.get("scripts", {}).get("build") == "vite build"
assert meta.get("schema") == "cadence-app-toolchain/1", meta
assert meta.get("tag") == tag and meta.get("source_sha") == source_sha, meta
assert meta.get("package_manager") == ui["packageManager"], meta
assert meta.get("pins") == expected_pins, (meta.get("pins"), expected_pins)
app_kit_dir = Path(ui_path).parent / "app-kit"
app_kit_files = {
    relative: hashlib.sha256((app_kit_dir / relative).read_bytes()).hexdigest()
    for relative in ("README.md", "package.json", "src/index.mjs", "src/receiver.mjs",
                     "src/refusal.mjs", "types/index.d.ts")
}
app_kit_version = json.loads((app_kit_dir / "package.json").read_text())["version"]
assert meta.get("app_kit") == {"version": app_kit_version, "files": app_kit_files}, meta.get("app_kit")
# Reject source-checkout paths or absolute host paths in any published text.
checkout = str(Path(ui_path).resolve().parent.parent)
for path in Path(sys.argv[2]).parent.rglob("*"):
    if path.is_file():
        data = path.read_bytes()
        text = data.decode("utf-8", "replace")
        assert checkout not in text and "/home/" not in text and "/workspace/" not in text, path
PY

# A separate, empty consumer uses only the unpacked release bytes.
consumer="$work/unpacked"
cat >"$consumer/index.html" <<'HTML'
<!doctype html><html><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0"><title>Consumer</title></head><body><div id="root"></div><script type="module" src="/src/main.jsx"></script></body></html>
HTML
mkdir "$consumer/src"
cat >"$consumer/src/main.jsx" <<'JS'
import React from 'react';
import { createRoot } from 'react-dom/client';
import '../frame-kit/kit.css';
createRoot(document.getElementById('root')).render(React.createElement('main', null, 'consumer build'));
JS
cat >"$consumer/vite.config.js" <<'JS'
import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
export default defineConfig({ plugins: [react()] });
JS
(cd "$consumer" && pnpm install --frozen-lockfile --ignore-scripts && pnpm build)
test -s "$consumer/dist/index.html"

# Run the exact inline publisher guard from ci.yml, not an imitation of it.
# Python only extracts this named run block; it does not parse/validate the workflow.
python3 - "$repo/.github/workflows/ci.yml" "$work/publisher-guard.sh" <<'PY'
import sys
from pathlib import Path
lines = Path(sys.argv[1]).read_text().splitlines()
name = "      - name: Re-check every tarball's sha256 and contents"
hits = [i for i, line in enumerate(lines) if line == name]
if len(hits) != 1:
    raise SystemExit(f"expected exactly one named production publisher guard; found {len(hits)}")
start = hits[0] + 1
while start < len(lines) and lines[start].strip() != "run: |":
    start += 1
if start == len(lines):
    raise SystemExit("named publisher guard has no literal run block")
start += 1
body = []
while start < len(lines):
    line = lines[start]
    if line and not line.startswith("          "):
        break
    body.append(line[10:] if line.startswith("          ") else "")
    start += 1
if not body or not any(line.strip() for line in body):
    raise SystemExit("named publisher guard run block is empty")
Path(sys.argv[2]).write_text("#!/usr/bin/env bash\n" + "\n".join(body) + "\n")
PY
chmod +x "$work/publisher-guard.sh"
fixture="$work/publisher-fixture"
mkdir -p "$fixture/dist" "$fixture/src/scripts" "$fixture/src/ui"
cp "$repo/scripts/install.sh" "$fixture/src/scripts/install.sh"
cp "$repo/ui/package.json" "$fixture/src/ui/package.json"
cp -R "$repo/ui/app-kit" "$fixture/src/ui/app-kit"
printf '# inert private fixture\n' > "$work/cadence"
printf 'fixture\n' > "$work/cadence.sha256"
printf '{"source_sha":"%s"}\n' "$source_sha" > "$work/manifest.json"
for target in x86_64-linux aarch64-linux aarch64-macos; do
  tar -czf "$fixture/dist/cadence-$tag-$target.tar.gz" -C "$work" cadence cadence.sha256 manifest.json
  (cd "$fixture/dist" && sha256sum "cadence-$tag-$target.tar.gz" > "cadence-$tag-$target.tar.gz.sha256")
done
cp "$archive" "$fixture/dist/$asset"
cp "$sidecar" "$fixture/dist/$asset.sha256"
(
  cd "$fixture/dist"
  TAG="$tag" SOURCE_SHA="$source_sha" bash "$work/publisher-guard.sh"
)
# Mutate the real helper-produced archive while retaining its original sidecar.
printf 'tamper' >> "$fixture/dist/$asset"
if (
  cd "$fixture/dist"
  TAG="$tag" SOURCE_SHA="$source_sha" bash "$work/publisher-guard.sh"
) >"$work/tamper.out" 2>&1; then
  echo 'production publisher guard accepted a tampered toolchain archive' >&2
  exit 1
fi
if ! grep -F -- "$asset: FAILED" "$work/tamper.out" >/dev/null; then
  echo "publisher guard failed for a reason other than checksum refusal of $asset:" >&2
  cat "$work/tamper.out" >&2
  exit 1
fi
# A recomputed sidecar must not hide modified receiver bytes: the guard has to
# reach its source comparison and refuse, not stop at the checksum.
repacked="$work/repacked"
mkdir "$repacked"
tar -xzf "$archive" -C "$repacked"
printf '\n// tampered\n' >> "$repacked/app-kit/src/receiver.mjs"
tar -czf "$fixture/dist/$asset" -C "$repacked" \
  LICENSE README.md frame-kit/frame.html frame-kit/kit.css frame-kit/metadata.json \
  package.json pnpm-lock.yaml toolchain.json \
  app-kit/README.md app-kit/package.json app-kit/src/index.mjs app-kit/src/receiver.mjs \
  app-kit/src/refusal.mjs app-kit/types/index.d.ts
(
  cd "$fixture/dist"
  sha256sum "$asset" > "$asset.sha256"
)
if (
  cd "$fixture/dist"
  TAG="$tag" SOURCE_SHA="$source_sha" bash "$work/publisher-guard.sh"
) >"$work/receiver-tamper.out" 2>&1; then
  echo 'production publisher guard accepted modified receiver bytes with a valid sidecar' >&2
  exit 1
fi
if ! grep -F 'app-kit archive bytes differ from source: src/receiver.mjs' "$work/receiver-tamper.out" >/dev/null; then
  echo 'publisher guard failed for a reason other than the receiver source mismatch:' >&2
  cat "$work/receiver-tamper.out" >&2
  exit 1
fi
printf '%s\n' 'CAD-1272 app-toolchain acceptance passed: package, clean consumer, checksum and receiver-byte guard refusals.'
